pub fn format_daily_title(lang: Lang, date: krono_core::daily::SimpleDate) -> String {
    match lang {
        Lang::Ru => {
            let genitive = match date.month {
                1 => "января",
                2 => "февраля",
                3 => "марта",
                4 => "апреля",
                5 => "мая",
                6 => "июня",
                7 => "июля",
                8 => "августа",
                9 => "сентября",
                10 => "октября",
                11 => "ноября",
                12 => "декабря",
                _ => "",
            };
            format!("{} {genitive} {}", date.day, date.year)
        }
        Lang::En => format!("{} {}, {}", month_name(Lang::En, date.month), date.day, date.year),
    }
}

pub fn format_daily_month_title(lang: Lang, year: i32, month: u32) -> String {
    format!("{} {year}", month_name(lang, month))
}

pub fn format_daily_year_title(lang: Lang, year: i32) -> String {
    match lang {
        Lang::Ru => format!("Дневник {year}"),
        Lang::En => format!("Diary {year}"),
    }
}

pub fn format_relative_time(lang: Lang, unix_ts: i64) -> String {
    if unix_ts <= 0 {
        return match lang {
            Lang::Ru => "недавно".to_string(),
            Lang::En => "recently".to_string(),
        };
    }
    // Support both legacy Unix seconds and Stage 3 millisecond mtimes transparently
    let ts_secs = if unix_ts > 100_000_000_000 {
        unix_ts / 1000
    } else {
        unix_ts
    };
    let now = chrono::Utc::now().timestamp();
    let diff = (now - ts_secs).max(0);
    match lang {
        Lang::Ru => {
            if diff < 60 {
                "только что".to_string()
            } else if diff < 3600 {
                format!("{} мин назад", diff / 60)
            } else if diff < 86400 {
                format!("{} ч назад", diff / 3600)
            } else if diff < 86400 * 7 {
                format!("{} д назад", diff / 86400)
            } else {
                chrono::DateTime::<chrono::Utc>::from_timestamp(ts_secs, 0)
                    .map(|dt| dt.format("%d.%m.%Y").to_string())
                    .unwrap_or_else(|| "—".to_string())
            }
        }
        Lang::En => {
            if diff < 60 {
                "just now".to_string()
            } else if diff < 3600 {
                format!("{}m ago", diff / 60)
            } else if diff < 86400 {
                format!("{}h ago", diff / 3600)
            } else if diff < 86400 * 7 {
                format!("{}d ago", diff / 86400)
            } else {
                chrono::DateTime::<chrono::Utc>::from_timestamp(ts_secs, 0)
                    .map(|dt| dt.format("%Y-%m-%d").to_string())
                    .unwrap_or_else(|| "—".to_string())
            }
        }
    }
}
